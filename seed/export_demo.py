"""Snapshot the seed user's listings into committed demo data.

Writes supabase/seed.sql (loaded automatically by `supabase start` / `supabase db reset`)
and copies the photos to frontend/public/demo/ so the demo works on any machine.
Run from the repo root after seed.py:  python seed/export_demo.py --email seed@student.ubc.ca
"""
import argparse
import json
import os
import sys

import httpx

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "backend"))

import db  # noqa: E402

PHOTO_DIR = os.path.join(ROOT, "frontend", "public", "demo")
SEED_SQL = os.path.join(ROOT, "supabase", "seed.sql")
COLUMNS = ["id", "seller_id", "campus_id", "type", "price", "title", "description", "tag", "condition",
           "condition_reason", "visible_defects", "photos", "pickup_point_id", "pickup_name", "lat", "lng",
           "embedding", "status", "created_at"]


def lit(v) -> str:
    """Python value -> SQL literal."""
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return "array[" + ", ".join(lit(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--email", required=True)
    args = parser.parse_args()

    user = db.get_user_by_email(args.email.lower())
    if not user:
        sys.exit(f"No user {args.email}; run seed/seed.py first.")
    rows = (db.client().table("listings").select(",".join(COLUMNS))
            .eq("seller_id", user["id"]).order("created_at").execute().data)

    os.makedirs(PHOTO_DIR, exist_ok=True)
    lines = [
        "-- Demo data generated by seed/export_demo.py. Photos live in frontend/public/demo/.",
        f"insert into users (id, email, name) values ({lit(user['id'])}, {lit(user['email'])}, {lit(user['name'])})",
        "  on conflict (id) do nothing;",
        "",
    ]
    for r in rows:
        local = []
        for url in r["photos"]:
            name = os.path.basename(url.split("?")[0])
            if not url.startswith("/demo/"):
                with open(os.path.join(PHOTO_DIR, name), "wb") as f:
                    f.write(httpx.get(url).raise_for_status().content)
            local.append(f"/demo/{name}")
        r["photos"] = local
        values = [lit(r[c]) for c in COLUMNS]
        values[COLUMNS.index("embedding")] = (
            "null" if r["embedding"] is None else lit(json.dumps(json.loads(r["embedding"]))) + "::vector"
        )
        lines.append(f"insert into listings ({', '.join(COLUMNS)}) values ({', '.join(values)})")
        lines.append("  on conflict (id) do nothing;")

    with open(SEED_SQL, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(rows)} listings to {os.path.relpath(SEED_SQL, ROOT)} "
          f"and photos to {os.path.relpath(PHOTO_DIR, ROOT)}/")


if __name__ == "__main__":
    main()
